class TranslationService:
    """Handles multilingual translation of automotive explanations."""

    def localize_explanation(
        self,
        explanation: SimpleExplanation,
        query: str,
        target_lang: str = "en"
    ) -> SimpleExplanation:
        """
        Returns localized explanation in the target language (en, kn, hi, ur, ml, ta, te).
        Preserves technical grounding and numerical telemetry.
        """
        lang = (target_lang or "en").lower().strip()
        if lang == "en":
            return explanation

        q_lower = query.lower()

        # Domain classification
        if any(w in q_lower for w in ["brake", "rotor", "pad", "stopping", "pedal", "ಬ್ರೇಕ್", "ब्रेक", "بریک", "ബ്രേക്ക്", "பிரேக்"]):
            domain = "brakes"
        elif any(w in q_lower for w in ["overheat", "temperature", "coolant", "radiator", "thermostat", "ಬಿಸಿ", "गरम", "گرم", "ചൂട്", "சூடு", "వేడి"]):
            domain = "overheating"
        elif any(w in q_lower for w in ["battery", "starter", "alternator", "crank", "click", "voltage", "ಬ್ಯಾಟರಿ", "बैटरी", "بیٹری", "ബാറ്ററി", "பேட்டரி"]):
            domain = "battery"
        elif any(w in q_lower for w in ["misfire", "p0300", "p0301", "stutter", "shaking", "spark", "idle", "मिसफायर", "స్పార్క్", "ஸ்பார்க்"]):
            domain = "misfire"
        else:
            domain = "general"

        if domain in MULTILINGUAL_EXPLANATION_TEMPLATES:
            lang_data = MULTILINGUAL_EXPLANATION_TEMPLATES[domain].get(lang)
            if lang_data:
                return SimpleExplanation(
                    what_does_it_mean=lang_data["what_does_it_mean"],
                    why_does_it_happen=lang_data["why_does_it_happen"],
                    symptoms_you_might_notice=lang_data["symptoms_you_might_notice"],
                    what_should_you_do=lang_data["what_should_you_do"],
                    when_to_visit_mechanic=lang_data["when_to_visit_mechanic"],
                    safety_warnings=lang_data["safety_warnings"],
                    suggested_mechanic_questions=lang_data["suggested_mechanic_questions"]
                )

        # Fallback to general template for the language
        if "general" in MULTILINGUAL_EXPLANATION_TEMPLATES:
            general_data = MULTILINGUAL_EXPLANATION_TEMPLATES["general"].get(lang)
            if general_data:
                return SimpleExplanation(
                    what_does_it_mean=general_data["what_does_it_mean"],
                    why_does_it_happen=general_data["why_does_it_happen"],
                    symptoms_you_might_notice=general_data["symptoms_you_might_notice"],
                    what_should_you_do=general_data["what_should_you_do"],
                    when_to_visit_mechanic=general_data["when_to_visit_mechanic"],
                    safety_warnings=general_data["safety_warnings"],
                    suggested_mechanic_questions=general_data["suggested_mechanic_questions"]
                )

        return explanation


_translation_service_instance = None


def get_translation_service() -> TranslationService:
    global _translation_service_instance
    if _translation_service_instance is None:
        _translation_service_instance = TranslationService()
    return _translation_service_instance
