class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem("autoassist_lang") || "en";
    if (!I18N_DICTIONARIES[this.currentLang]) {
      this.currentLang = "en";
    }
  }

  setLanguage(langCode) {
    if (!I18N_DICTIONARIES[langCode]) return;
    this.currentLang = langCode;
    localStorage.setItem("autoassist_lang", langCode);
    this.applyToDOM();
    if (window.voiceManager) {
      window.voiceManager.updateLanguage(langCode);
    }
  }

  t(key, fallback = "") {
    const dict = I18N_DICTIONARIES[this.currentLang] || I18N_DICTIONARIES.en;
    if (dict[key] !== undefined) return dict[key];
    if (I18N_DICTIONARIES.en[key] !== undefined) return I18N_DICTIONARIES.en[key];
    return fallback || key;
  }

  applyToDOM() {
    const dict = I18N_DICTIONARIES[this.currentLang] || I18N_DICTIONARIES.en;
    const isRtl = dict.dir === "rtl";

    document.documentElement.lang = this.currentLang;
    document.documentElement.dir = dict.dir || "ltr";

    if (isRtl) {
      document.body.classList.add("rtl-layout");
    } else {
      document.body.classList.remove("rtl-layout");
    }

    // Translate all elements with data-i18n
    const elements = document.querySelectorAll("[data-i18n]");
    elements.forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const translation = this.t(key);
      if (translation) {
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
          el.placeholder = translation;
        } else {
          el.textContent = translation;
        }
      }
    });

    // Translate all elements with data-i18n-title
    const titleElements = document.querySelectorAll("[data-i18n-title]");
    titleElements.forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      const translation = this.t(key);
      if (translation) {
        el.title = translation;
      }
    });

    // Translate placeholders
    const placeholderElements = document.querySelectorAll("[data-i18n-placeholder]");
    placeholderElements.forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      const translation = this.t(key);
      if (translation) {
        el.placeholder = translation;
      }
    });

    // Update active state on language selector dropdown
    const langSelect = document.getElementById("header-language-select");
    if (langSelect && langSelect.value !== this.currentLang) {
      langSelect.value = this.currentLang;
    }
  }
}

window.i18n = new I18nManager();
